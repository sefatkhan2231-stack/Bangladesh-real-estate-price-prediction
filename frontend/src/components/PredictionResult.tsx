const PredictionResult = ({ prediction }) => {
  if (!prediction) {
    return null;
  }

  const formattedPrice = new Intl.NumberFormat("en-BD", {
    style: "currency",
    currency: "BDT",
    maximumFractionDigits: 0,
  }).format(prediction.predicted_price);

  return (
    <div className="bg-gradient-to-br from-emerald-500 to-teal-700 text-white rounded-2xl p-6 md:p-8 shadow-xl flex flex-col justify-center items-center text-center transition-all duration-300 transform hover:scale-[1.01]">
      <div className="inline-flex items-center gap-2 bg-white/20 backdrop-blur-md px-3 py-1 rounded-full text-xs font-semibold uppercase tracking-wider mb-4">
        <span>✨ AI Valuation Result</span>
      </div>

      <h2 className="text-emerald-100 text-sm font-medium uppercase tracking-widest mb-1">
        Estimated Sale Price
      </h2>

      <h1 className="text-4xl md:text-5xl font-extrabold tracking-tight mb-4 text-white">
        {formattedPrice}
      </h1>

      <p className="text-emerald-100 text-sm max-w-md leading-relaxed">
        This is an estimated property sale price generated by the XGBoost
        machine learning model based on current market features.
      </p>
    </div>
  );
};

export default PredictionResult;
